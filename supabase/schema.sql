-- Community Tasks intentionally uses public, anonymous lists.
-- Do not store sensitive information in this application.

create table if not exists public.lists (
  id bigint generated by default as identity primary key,
  uuid uuid not null unique,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  task_text text not null,
  list_id bigint not null references public.lists(id) on delete cascade,
  complete boolean not null default false,
  created_at timestamptz not null default timezone('utc', now())
);

create index if not exists tasks_list_id_id_idx on public.tasks (list_id, id desc);

alter table public.lists enable row level security;
alter table public.tasks enable row level security;
alter table public.tasks replica identity full;

drop policy if exists "Public lists can be read" on public.lists;
create policy "Public lists can be read"
  on public.lists for select
  to anon, authenticated
  using (true);

drop policy if exists "Public lists can be created" on public.lists;
create policy "Public lists can be created"
  on public.lists for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Public tasks can be read" on public.tasks;
create policy "Public tasks can be read"
  on public.tasks for select
  to anon, authenticated
  using (true);

drop policy if exists "Public tasks can be created" on public.tasks;
create policy "Public tasks can be created"
  on public.tasks for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Public tasks can be updated" on public.tasks;
create policy "Public tasks can be updated"
  on public.tasks for update
  to anon, authenticated
  using (true)
  with check (true);

grant usage on schema public to anon, authenticated;
grant select, insert on public.lists to anon, authenticated;
grant select, insert, update on public.tasks to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'tasks'
  ) then
    alter publication supabase_realtime add table public.tasks;
  end if;
end
$$;
